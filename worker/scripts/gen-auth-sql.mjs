// Writes migrations/0001_auth.sql: Better Auth's tables as SQLite DDL, compiled from the
// same options the Worker runs with (src/auth.js), against an empty in-memory database.
// D1 cannot be reached by Better Auth's own CLI, so this is how its schema gets into a
// wrangler migration. Run it again after upgrading Better Auth and diff the result.
import { DatabaseSync } from 'node:sqlite';
import { writeFileSync } from 'node:fs';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../src/auth.js';

const db = new DatabaseSync(':memory:');
const { compileMigrations } = await getMigrations(authOptions({ BASE_URL: 'https://maclaine.se', BETTER_AUTH_SECRET: 'x'.repeat(32) }, db));
const sql = await compileMigrations();
writeFileSync(new URL('../migrations/0001_auth.sql', import.meta.url), '-- Better Auth tables. GENERATED by scripts/gen-auth-sql.mjs, do not edit by hand.\n' + sql.trim() + '\n');
console.log(sql);
